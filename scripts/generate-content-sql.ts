/**
 * Generates supabase/migrations/20261118000005_initial_content.sql from src/lib/content/defaults.ts
 * and src/lib/email/templates.ts so the CMS starts with the brief's copy. Run: npm run content:sql
 */
import { writeFileSync } from "node:fs";
import { DEFAULT_SETTINGS, PAGES, SECTION_DEFAULTS, FAQ_DEFAULTS } from "../src/lib/content/defaults";
import { EMAIL_TEMPLATE_DEFAULTS } from "../src/lib/email/templates";

const q = (v: string | null) => (v === null ? "null" : `'${v.replace(/'/g, "''")}'`);
const j = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;

const out: string[] = [
  "-- GENERATED by scripts/generate-content-sql.ts — initial CMS content from the designer brief.",
  "-- Uses ON CONFLICT DO NOTHING so organiser edits are never overwritten by re-running.",
  "",
  `insert into public.events (slug, name, timezone) values ('mr-indianz-2027', 'Mr. IndiaNZ 2027', 'Pacific/Auckland') on conflict (slug) do nothing;`,
];
for (const [key, value] of Object.entries(DEFAULT_SETTINGS)) {
  out.push(`insert into public.site_settings (key, published, published_at) values (${q(key)}, ${j(value)}, now()) on conflict (key) do nothing;`);
}
for (const p of PAGES) {
  out.push(`insert into public.content_pages (slug, title, meta_description) values (${q(p.slug)}, ${q(p.title)}, ${q(p.metaDescription)}) on conflict (slug) do nothing;`);
}
for (const s of SECTION_DEFAULTS) {
  out.push(`insert into public.content_sections (page_slug, key, sort_order, published, approval_status, published_at) values (${q(s.page)}, ${q(s.key)}, ${s.sortOrder}, ${j(s.content)}, ${q(s.approvalStatus)}, now()) on conflict (page_slug, key) do nothing;`);
}
out.push("insert into public.faqs (question, answer, category, sort_order, is_published, approval_status)");
out.push("select v.question, v.answer, v.category, v.sort_order, true, v.approval_status from (values");
out.push(FAQ_DEFAULTS.map((f, i) => `  (${q(f.question)}, ${q(f.answer)}, ${q(f.category)}, ${(i + 1) * 10}, ${q(f.approvalStatus)})`).join(",\n"));
out.push(") as v(question, answer, category, sort_order, approval_status)");
out.push("where not exists (select 1 from public.faqs);");
for (const t of EMAIL_TEMPLATE_DEFAULTS) {
  out.push(`insert into public.email_templates (key, name, subject, body, description) values (${q(t.key)}, ${q(t.name)}, ${q(t.subject)}, ${q(t.body)}, ${q(t.description)}) on conflict (key) do nothing;`);
}
out.push(`
-- People's Choice campaign for 2027: created in DRAFT (not public). Packages are DEMONSTRATION VALUES
-- copied from the reference voting model and are NOT approved Mr. IndiaNZ prices.
insert into public.voting_campaigns (slug, name, status, is_demo, rules_version, price_note)
values ('peoples-choice-2027', 'People''s Choice Award 2027', 'draft', false, 'draft-2026-11',
        'Demonstration pricing — package prices, GST and processing-fee treatment are pending organiser approval.')
on conflict (slug) do nothing;
insert into public.voting_packages (campaign_id, name, display_label, price_cents, votes, sort_order, is_demo_value)
select c.id, v.name, v.label, v.price_cents, v.votes, v.sort_order, true
  from public.voting_campaigns c,
       (values ('Starter', 'Demonstration value', 400, 20, 10), ('Supporter', 'Demonstration value', 1000, 50, 20),
               ('Champion', 'Demonstration value', 2200, 120, 30), ('Premium', 'Demonstration value', 5000, 300, 40),
               ('Ultimate', 'Demonstration value', 10000, 700, 50)) as v(name, label, price_cents, votes, sort_order)
 where c.slug = 'peoples-choice-2027'
   and not exists (select 1 from public.voting_packages p where p.campaign_id = c.id);
`);
writeFileSync("supabase/migrations/20261118000005_initial_content.sql", out.join("\n") + "\n");
console.log("wrote initial content migration");
